/**
 * Matriz de Permisos Frontend para Vakera (RBAC)
 */
export const ROLES = {
  DUENO: "dueno",
  CAPATAZ: "capataz",
  PEON: "peon",
  OFICINA: "oficina",
  VETERINARIO: "veterinario",
};

export const PERMISOS = {
  // Módulos
  VER_DASHBOARD_EJECUTIVO: [ROLES.DUENO, ROLES.OFICINA],
  GESTION_USUARIOS_ROLES: [ROLES.DUENO],
  VER_SANIDAD_VACUNAS: [ROLES.DUENO, ROLES.CAPATAZ, ROLES.VETERINARIO, ROLES.OFICINA],
  EDITAR_SANIDAD_VACUNAS: [ROLES.DUENO, ROLES.VETERINARIO],
  VER_INVENTARIO_INSUMOS: [ROLES.DUENO, ROLES.CAPATAZ, ROLES.OFICINA, ROLES.VETERINARIO],
  ORDENAR_REPOSICION: [ROLES.DUENO, ROLES.OFICINA],
  VER_PARTES_DIARIOS: [ROLES.DUENO, ROLES.CAPATAZ, ROLES.PEON, ROLES.OFICINA, ROLES.VETERINARIO],
  CREAR_PARTE_DIARIO: [ROLES.PEON, ROLES.CAPATAZ, ROLES.DUENO],
  APROBAR_PARTE_DIARIO: [ROLES.CAPATAZ, ROLES.DUENO],
};

export function tienePermiso(rolUsuario, permiso) {
  if (!rolUsuario || !PERMISOS[permiso]) return false;
  return PERMISOS[permiso].includes(rolUsuario);
}
